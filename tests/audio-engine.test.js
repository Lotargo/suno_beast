const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const { execFileSync } = require('node:child_process');
const AudioEngine = require('../native/audio-engine');
test('MP3 stream copy preserves encoded audio when trimming is off', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'suno-copy-test-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const source = path.join(dir, 'source.mp3');
  execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=330:duration=0.5', '-c:a', 'libmp3lame', source], { windowsHide: true });
  const hash = file => execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-map', '0:a', '-c:a', 'copy', '-f', 'hash', '-hash', 'sha256', '-'], { encoding: 'utf8', windowsHide: true }).trim();
  const expected = hash(source);
  const output = await new AudioEngine({ outputDir: dir }).processAndTrimAudio(source, { title: 'Copy check' }, { format: 'mp3', trimSilence: false, copyAudio: true });
  assert.equal(hash(output.filePath), expected);
});
test('real MP3 embeds full lyrics, style and cover; a broken optional cover cannot lose audio', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'suno-tags-test-'));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  const source = path.join(dir, 'source.webm'), cover = path.join(dir, 'cover.png');
  execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=2', '-c:a', 'libopus', source], { windowsHide: true });
  execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'color=c=orange:s=64x64', '-frames:v', '1', cover], { windowsHide: true });
  const lyrics = '[Verse]\nПолный текст песни\n'.repeat(80);
  const metadata = { title: 'Cover check', artist: 'QA', album: 'Real album from Suno', tags: 'dark electro, tribal', lyrics, image_url: 'https://cdn2.suno.ai/cover.png' };
  const engine = new AudioEngine({ outputDir: dir, downloadCover: async (_, dest) => fs.copyFileSync(cover, dest) });
  const output = await engine.processAndTrimAudio(source, metadata, { format: 'mp3', trimSilence: true });
  const probe = JSON.parse(execFileSync('ffprobe', ['-v', 'error', '-show_streams', '-show_format', '-of', 'json', output.filePath], { encoding: 'utf8', windowsHide: true }));
  assert.equal(output.coverEmbedded, true); assert.equal(probe.format.tags.lyrics, lyrics);
  assert.equal(probe.format.tags.genre, 'dark electro, tribal');
  assert.equal(probe.format.tags.album, 'Real album from Suno');
  assert.ok(probe.streams.some(stream => stream.codec_type === 'video' && stream.disposition.attached_pic === 1));
  assert.ok(Number(probe.format.duration) > 1.9, 'embedding artwork must not truncate the song');
  const rawAgain = path.join(dir, 'second.webm');
  execFileSync('ffmpeg', ['-v', 'error', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=1', '-c:a', 'libopus', rawAgain], { windowsHide: true });
  engine.downloadCover = async (_, dest) => fs.writeFileSync(dest, 'broken image');
  const fallback = await engine.processAndTrimAudio(rawAgain, metadata, { format: 'mp3', trimSilence: false });
  assert.equal(fallback.coverEmbedded, false); assert.ok(fs.statSync(fallback.filePath).size > 0);
});
